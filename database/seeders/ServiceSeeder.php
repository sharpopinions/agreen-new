        $uk = Language::where('code', 'uk')->value('id');
        if (! $uk) {
            return;
        }

        foreach ($this->services() as $i => [$icon, $title, $summary, $details, $extra]) {
            if (Service::whereHas('translations', fn($q) => $q->where('title', $title))->exists()) {
                continue;
            }
            $service = Service::create(['icon' => $icon, 'sort_order' => $i, 'is_active' => true]);
            $service->translations()->create($extra + [
                'language_id' => $uk,
                'title'       => $title,
                'slug'        => Str::slug($title),
                'summary'     => $summary,
                'details'     => $details,
            ]);
