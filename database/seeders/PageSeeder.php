    public function run(): void
    {
        $uk = Language::where('code', 'uk')->value('id');
        if (! $uk) {
            return;
        }

        foreach ($this->pages() as $i => [$key, $layout, $slug, $title, $blocks]) {
            if (Page::where('key', $key)->exists()) {
                continue;
            }
            $page = Page::create(['key' => $key, 'layout' => $layout, 'sort_order' => $i, 'is_active' => true]);
            $page->translations()->create([
                'language_id' => $uk,
                'title'       => $title,
                'slug'        => $slug,
                'blocks'      => $blocks,
            ]);
        }
    }

    private static function block(string $type, array $data): array
    {
        return ['type' => $type, 'data' => $data];
    }

